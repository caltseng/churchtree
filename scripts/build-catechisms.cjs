const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const books = [
  { route: 'wsc', title: 'Westminster Shorter Catechism', count: 107, pages: '285–314' },
  { route: 'wlc', title: 'Westminster Larger Catechism', count: 196, pages: '127–281' },
];
const escape = value => value.replace(/[&<>"']/g, character => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[character]);

for (const book of books) {
  const { route, title, count, pages } = book;
  const other = books.find(candidate => candidate !== book);
  const folder = path.join(root, route);
  const entries = JSON.parse(fs.readFileSync(path.join(folder, 'questions.json'), 'utf8'));
  if (entries.length !== count || entries.some(({ number, question, answer }, index) =>
    number !== index + 1 || !question?.trim() || !answer?.trim())) {
    throw new Error(`Invalid question sequence or text for ${title}`);
  }

  const ranges = Array.from({ length: Math.ceil(count / 10) }, (_, index) => {
    const start = index * 10 + 1;
    return `<li><a href="#q-${start}">${start}–${Math.min(start + 9, count)}</a></li>`;
  }).join('\n');
  const questions = entries.map(({ number, question, answer }) => `      <article id="q-${number}" tabindex="-1">
        <h2><a href="#q-${number}">Q. ${number}.</a> ${escape(question)}</h2>
        <p><b>A.</b> ${escape(answer)}</p>
      </article>`).join('\n');

  fs.writeFileSync(path.join(folder, 'index.html'), `<!doctype html>
<!-- Generated by scripts/build-catechisms.cjs. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="Read all ${count} questions and answers of the ${title} in the historical 1860 English edition.">
  <title>${title} · Main Branch</title>
  <link rel="canonical" href="https://main-branch.com/${route}/">
  <link rel="icon" type="image/svg+xml" href="../assets/brand/logos/main-branch.svg">
  <link rel="stylesheet" href="../theme.css">
  <link rel="stylesheet" href="../brand.css">
  <link rel="stylesheet" href="../catechisms.css">
  <script src="../theme.js"></script>
</head>
<body class="catechism">
  <a class="skip" href="#reading">Skip to questions</a>
  <header class="catechism-header">
    <a class="main-branch-brand" href="../" aria-label="Main Branch home">
      <img class="main-branch-symbol" src="../assets/brand/logos/main-branch.svg" width="44" height="44" alt="">
      <span class="main-branch-copy">Main Branch</span>
    </a>
    <nav aria-label="Related Westminster readings">
      <a href="../wcf/">Westminster Confession of Faith</a>
      <a href="../${other.route}/">${other.title}</a>
    </nav>
  </header>
  <main>
    <div class="catechism-intro">
      <h1>${title}</h1>
      <p>${count} questions and answers · <a href="#sources">1860 English edition</a></p>
      <nav class="question-index" aria-label="Question ranges">
        <h2>Jump to questions</h2>
        <ul>${ranges}</ul>
      </nav>
    </div>
    <section id="reading" aria-label="Questions and answers" tabindex="-1">
${questions}
    </section>
    <footer id="sources">
      <h2>About this edition</h2>
      <p>The Westminster Assembly’s English text is presented from <cite>The Confession of Faith; the Larger and Shorter Catechisms, with the Scripture-Proofs at Large</cite> (London: T. Nelson and Sons, 1860), pp. ${pages}. The reader contains the complete questions and answers. Scripture proof notes are available in the scanned edition.</p>
      <p>The historical text is in the U.S. public domain. The digital transcription is from Ian Buchanan’s Confessions Corpus and is available under CC0 1.0.</p>
      <ul>
        <li><a href="https://archive.org/details/confessionoffait00westuoft/page/${pages.split('–')[0]}/mode/2up">Read the scanned 1860 edition</a></li>
        <li><a href="https://github.com/iandbuchanan/confessions-corpus/blob/01ed626ffaabccbe14f3df3ff25c3e7b1b7935d6/LICENSE-TEXTS.md">Transcription and reuse terms</a></li>
        <li><a href="#reading">Return to the questions</a></li>
      </ul>
    </footer>
  </main>
</body>
</html>
`);
  console.log(`Built ${title}: ${count} questions.`);
}
